end

T['reload refreshes the policy without a restart'] = function()
  write_config({ 'unzoom_on_nav=true', 'most_recently_focused=false' })

  local result = child.lua_func(function()
    vim.notify = function() end
    local config = require('herdr-splits.config')
    config.setup({ at_edge = 'stop' })
    local before = {
      unzoom_on_nav = config.unzoom_on_nav,
      most_recently_focused = config.most_recently_focused,
    }

    local path = vim.env.HERDR_SPLITS_CONFIG
    vim.fn.writefile({ 'unzoom_on_nav=false', 'most_recently_focused=true' }, path)
    local report = config.reload()

    return {
      before = before,
      report = report,
      unzoom_on_nav = config.unzoom_on_nav,
      most_recently_focused = config.most_recently_focused,
      at_edge = config.at_edge,
    }
  end)

  expect.equality(result.before, { unzoom_on_nav = true, most_recently_focused = false })
  expect.equality(result.unzoom_on_nav, false)
  expect.equality(result.most_recently_focused, true)
  expect.equality(result.report.policy_changed, true)
  expect.equality(result.report.chords_changed, false)
  -- Non-managed opts are not touched by a reload.
  expect.equality(result.at_edge, 'stop')
end
T['booleans are matched case-insensitively, like the other readers'] = function()
  -- Rust (`eq_ignore_ascii_case`), Python (`lower()`) and Vim all accept
  -- `FALSE`; the Lua reader must not be the odd one out.
  write_config({ 'unzoom_on_nav=FALSE', 'most_recently_focused=True' })

  local result = child.lua_func(function()
    local values = require('herdr-splits.conf').read_managed()
    return { unzoom = values.unzoom_on_nav, mru = values.most_recently_focused }
  end)

  expect.equality(result, { unzoom = false, mru = true })
end

T['reload rewrites the conf in overwrite mode, so the helper cannot drift'] = function()
  -- Hand-written `stop` (now the non-default value) is adopted by setup(); the
  -- projection is written, the file and this session agree. A later edit of the
  -- file must not leave the helper (which reads the file per keypress) on a
  -- different value.
  write_config({ 'nav_at_edge=stop' })

  local result = child.lua_func(function()
    vim.notify = function() end
    local config = require('herdr-splits.config')
    local path = vim.env.HERDR_SPLITS_CONFIG
    local function read_file()
      local file = assert(io.open(path, 'r'))
      local bytes = file:read('*a')
      file:close()
      return bytes
    end

    config.setup({ overwrite_conf = true })
    local after_setup = read_file()

    vim.fn.writefile({ 'nav_at_edge=wrap' }, path)
    local report = config.reload()

    return {
      after_setup = after_setup,
      after_reload = read_file(),
      nav_at_edge = config.nav_at_edge,
      policy_changed = report.policy_changed,
    }
  end)

  -- setup() adopted the hand-written value and published it.
  expect.equality(result.after_setup:find('nav_at_edge=stop', 1, true) ~= nil, true)
  -- reload() re-projects defaults + opts, and rewrites the file to match.
  expect.equality(result.nav_at_edge, 'wrap')
  expect.equality(result.after_reload:find('nav_at_edge=wrap', 1, true) ~= nil, true)
  expect.equality(result.after_reload:find('nav_at_edge=stop', 1, true), nil)
  expect.equality(result.policy_changed, true)
end

return T

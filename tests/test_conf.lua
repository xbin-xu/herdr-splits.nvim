T['setup with overwrite_conf writes the resolved set and reverts dropped opts'] = function()
  write_config({ 'nav_key_left=ctrl+legacy', 'resize_key_left=alt+legacy', 'unzoom_on_nav=false' })

  local result = child.lua_func(function()
    local notices = {}
    vim.notify = function(msg) notices[#notices + 1] = msg end
    local config = require('herdr-splits.config')

    config.setup({
      overwrite_conf = true,
      nav_keys = { left = '<C-x>' },
      unzoom_on_nav = true,
    })
    local first = {
      nav_left = config.nav_keys.left,
      resize_left = config.resize_keys.left,
      unzoom_on_nav = config.unzoom_on_nav,
      nav_at_edge = config.nav_at_edge,
      notices = vim.deepcopy(notices),
    }

    -- Second call drops both managed opts: setup() is authoritative, so the
    -- generated file is not read back and the values revert to the defaults.
    config.setup({ overwrite_conf = true })
    local second = {
      nav_left = config.nav_keys.left,
      resize_left = config.resize_keys.left,
      unzoom_on_nav = config.unzoom_on_nav,
      nav_at_edge = config.nav_at_edge,
    }

    return { first = first, second = second }
  end)

  -- The first call adopted the hand-written values it was handed, and said so.
  expect.equality(result.first.nav_left, 'ctrl+x')
  expect.equality(result.first.resize_left, 'alt+legacy')
  expect.equality(result.first.unzoom_on_nav, true)
  expect.equality(result.first.nav_at_edge, 'wrap')
  expect.equality(#result.first.notices, 1)
  expect.equality(result.first.notices[1]:find('hand-written', 1, true) ~= nil, true)

  expect.equality(result.second, {
    nav_left = 'ctrl+h',
    resize_left = 'alt+h',
    -- Dropped opt reverts to the shipped default (`false`), which is also what
    -- makes this different from the value the first call wrote.
    unzoom_on_nav = false,
    nav_at_edge = 'wrap',
  })
end


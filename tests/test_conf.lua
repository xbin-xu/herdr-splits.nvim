local T
local expect = MiniTest.expect
local child = MiniTest.new_child_neovim()

local source = debug.getinfo(1, 'S').source
local root = vim.fn.fnamemodify(source:sub(2), ':p:h:h')

local function write_config(lines)
  child.lua_func(function(config_lines)
    local path = vim.env.HERDR_SPLITS_CONFIG
    vim.fn.mkdir(vim.fn.fnamemodify(path, ':h'), 'p')
    vim.fn.writefile(config_lines, path)
  end, lines)
end

T = MiniTest.new_set({
  hooks = {
    pre_case = function()
      child.restart({ '--noplugin', '-u', 'NONE', '-i', 'NONE' })
      child.cmd('set runtimepath^=' .. vim.fn.fnameescape(root))
      child.lua([[
        local test_dir = vim.fn.tempname()
        vim.fn.mkdir(test_dir, 'p')
        vim.g.herdr_splits_test_dir = test_dir
        vim.env.HOME = test_dir .. '/home'
        vim.env.XDG_CONFIG_HOME = test_dir .. '/xdg'
        vim.env.HERDR_SPLITS_CONFIG = test_dir .. '/nested/herdr-splits.conf'
        vim.env.HERDR_BIN_PATH = test_dir .. '/missing-herdr'
        vim.env.HERDR_PLUGIN_CONFIG_DIR = nil
      ]])
    end,
    post_case = function()
      local test_dir = child.g.herdr_splits_test_dir
      child.stop()
      vim.fn.delete(test_dir, 'rf')
    end,
  },
})

T['to_herdr translates key notation'] = function()
  local translate = function(value)
    return child.lua_func(function(key)
      return require('herdr-splits.conf').to_herdr(key)
    end, value)
  end

  expect.equality(translate('<C-M-Left>'), 'ctrl+alt+left')
  expect.equality(translate('<A-Return>'), 'alt+enter')
  expect.equality(translate('<S-Space>'), 'shift+space')
  expect.equality(translate('H'), 'h')
  expect.equality(translate('<Escape>'), 'esc')
  expect.equality(translate(''), vim.NIL)
  expect.equality(translate(false), vim.NIL)
  expect.equality(translate('<C>'), vim.NIL)
end

T['to_nvim inverts to_herdr (canonical spellings)'] = function()
  local roundtrip = function(value)
    return child.lua_func(function(key)
      local conf = require('herdr-splits.conf')
      return conf.to_nvim(conf.to_herdr(key))
    end, value)
  end

  expect.equality(roundtrip('<C-h>'), '<C-h>')
  expect.equality(roundtrip('<M-l>'), '<M-l>')
  expect.equality(roundtrip('<C-M-Left>'), '<C-M-Left>')
  expect.equality(roundtrip('<S-Space>'), '<S-Space>')
  expect.equality(roundtrip('h'), 'h')
  -- `enter` is the normalised spelling (both <Return> and <Enter> map to it).
  expect.equality(roundtrip('<A-Return>'), '<M-CR>')
  expect.equality(child.lua_func(function()
    return require('herdr-splits.conf').to_nvim(nil)
  end), vim.NIL)
end

T['read_managed handles a missing file'] = function()
  local result = child.lua_func(function()
    local values, adopted = require('herdr-splits.conf').read_managed()
    return { adopted = adopted, count = vim.tbl_count(values) }
  end)

  expect.equality(result, { adopted = false, count = 0 })
end

T['read_managed adopts managed legacy values with last value winning'] = function()
  write_config({
    '# legacy config',
    ' nav_key_left = ctrl+old',
    'nav_key_left=ctrl+new # last value wins',
    'resize_key_up = alt+up',
    'unzoom_on_nav=false',
    'nav_at_edge=stop',
    'most_recently_focused=true',
    'unknown_key=ignored',
  })

  local result = child.lua_func(function()
    local values, adopted = require('herdr-splits.conf').read_managed()
    return {
      adopted = adopted,
      nav_left = values.nav_keys.left,
      resize_up = values.resize_keys.up,
      unzoom_on_nav = values.unzoom_on_nav,
      nav_at_edge = values.nav_at_edge,
      most_recently_focused = values.most_recently_focused,
      unknown = values.unknown_key,
    }
  end)

  expect.equality(result, {
    adopted = true,
    nav_left = 'ctrl+new',
    resize_up = 'alt+up',
    unzoom_on_nav = false,
    nav_at_edge = 'stop',
    most_recently_focused = true,
  })
end

T['write creates generated content without leftover temporary files'] = function()
  local result = child.lua_func(function()
    local conf = require('herdr-splits.conf')
    local ok, err = conf.write({
      nav_keys = { left = 'ctrl+h', down = 'ctrl+j', up = 'ctrl+k', right = 'ctrl+l' },
      resize_keys = { left = 'alt+h', down = 'alt+j', up = 'alt+k', right = 'alt+l' },
      unzoom_on_nav = false,
      nav_at_edge = 'stop',
      most_recently_focused = false,
    })
    -- `true` = setup()-authoritative: our own generated output is not read back.
    local values, found = conf.read_managed(true)
    return {
      ok = ok,
      err = err,
      found = found,
      count = vim.tbl_count(values),
    }
  end)

  expect.equality(result, { ok = true, found = false, count = 0 })

  local content = child.lua_func(function()
    local file = assert(io.open(vim.env.HERDR_SPLITS_CONFIG, 'r'))
    local bytes = file:read('*a')
    file:close()
    return bytes
  end)
  expect.equality(content, table.concat({
    '# herdr-splits-generated-v1',
    '# herdr-splits plugin config — GENERATED by herdr-splits.nvim setup().',
    '# Written because setup({ overwrite_conf = true }): this file is a projection',
    '# of the Lua options and is regenerated on every setup() — remove an opt in',
    '# setup() to revert it to the default.',
    '#',
    '# To make this file yours: delete the marker line above (and set',
    '# overwrite_conf = false, the default). setup() then reads it as the instance',
    '# policy and never overwrites it. `herdr-splits init` writes a fresh scaffold.',
    'nav_key_left=ctrl+h',
    'nav_key_down=ctrl+j',
    'nav_key_up=ctrl+k',
    'nav_key_right=ctrl+l',
    'resize_key_left=alt+h',
    'resize_key_down=alt+j',
    'resize_key_up=alt+k',
    'resize_key_right=alt+l',
    'unzoom_on_nav=false',
    'nav_at_edge=stop',
    'most_recently_focused=false',
    '',
  }, '\n'))
  expect.equality(child.lua_get([[vim.fn.glob(vim.env.HERDR_SPLITS_CONFIG .. '.tmp.*', false, true)]]), {})
end

T['read_managed honours a generated file when the conf is the authority'] = function()
  -- A file an older setup() generated must still be honoured by default: the
  -- upgrade path from the setup()-authoritative era may not silently reset
  -- someone's policy to the defaults.
  write_config({
    '# herdr-splits-generated-v1',
    'unzoom_on_nav=false',
    'most_recently_focused=true',
  })

  local result = child.lua_func(function()
    local values, found = require('herdr-splits.conf').read_managed()
    return { found = found, unzoom = values.unzoom_on_nav, mru = values.most_recently_focused }
  end)

  expect.equality(result, { found = true, unzoom = false, mru = true })
end

T['write takes over a headerless conf and stamps the marker'] = function()
  write_config({ '# mine', 'unzoom_on_nav=false' })

  local result = child.lua_func(function()
    local conf = require('herdr-splits.conf')
    local ok = conf.write({
      nav_keys = { left = 'ctrl+h', down = 'ctrl+j', up = 'ctrl+k', right = 'ctrl+l' },
      resize_keys = { left = 'alt+h', down = 'alt+j', up = 'alt+k', right = 'alt+l' },
      unzoom_on_nav = true,
      nav_at_edge = 'wrap',
      most_recently_focused = false,
    })
    local file = assert(io.open(vim.env.HERDR_SPLITS_CONFIG, 'r'))
    local bytes = file:read('*a')
    file:close()
    return { ok = ok, generated = conf.is_generated(bytes), unzoom = bytes:find('unzoom_on_nav=true', 1, true) ~= nil }
  end)

  -- write() is only reachable with overwrite_conf, i.e. after the user asked
  -- setup() to own the file; it then takes it over and stamps the marker.
  expect.equality(result, { ok = true, generated = true, unzoom = true })
end

T['setup reads the conf and never writes it (file authority)'] = function()
  write_config({
    '# mine',
    'nav_key_left=ctrl+legacy',
    'resize_key_left=alt+legacy',
    'unzoom_on_nav=false',
    'nav_at_edge=stop',
    'most_recently_focused=true',
  })

  local result = child.lua_func(function()
    vim.notify = function() end
    local config = require('herdr-splits.config')
    config.setup({ at_edge = 'split' })
    local file = assert(io.open(vim.env.HERDR_SPLITS_CONFIG, 'r'))
    local bytes = file:read('*a')
    file:close()
    return {
      nav_left = config.nav_keys.left,
      resize_left = config.resize_keys.left,
      unzoom_on_nav = config.unzoom_on_nav,
      nav_at_edge = config.nav_at_edge,
      most_recently_focused = config.most_recently_focused,
      -- Non-managed opts still merge as before.
      at_edge = config.at_edge,
      overwrite_conf = config.overwrite_conf,
      bytes = bytes,
    }
  end)

  expect.equality(result, {
    nav_left = 'ctrl+legacy',
    resize_left = 'alt+legacy',
    unzoom_on_nav = false,
    nav_at_edge = 'stop',
    most_recently_focused = true,
    at_edge = 'split',
    overwrite_conf = false,
    bytes = table.concat({
      '# mine',
      'nav_key_left=ctrl+legacy',
      'resize_key_left=alt+legacy',
      'unzoom_on_nav=false',
      'nav_at_edge=stop',
      'most_recently_focused=true',
      '',
    }, '\n'),
  })
end

